<#
.SYNOPSIS
    Generates bench/REPORT.md: the final benchmark (results.csv) compared with the baseline (baseline.csv).

.EXAMPLE
    .\bench\make-report.ps1
    .\bench\make-report.ps1 -Results bench\results.csv -Baseline bench\baseline.csv -Output bench\REPORT.md
#>
[CmdletBinding()]
param(
    [string]$Baseline = '',
    [string]$Results = '',
    [string]$Output = ''
)

$ErrorActionPreference = 'Stop'
$here = if ($PSScriptRoot) { $PSScriptRoot } else { Split-Path -Parent $MyInvocation.MyCommand.Path }
if (-not $Baseline) { $Baseline = Join-Path $here 'baseline.csv' }
if (-not $Results) { $Results = Join-Path $here 'results.csv' }
if (-not $Output) { $Output = Join-Path $here 'REPORT.md' }
$inv = [Globalization.CultureInfo]::InvariantCulture
# Multiplication sign; the script stays ASCII (Windows PowerShell 5.1 reads BOM-less scripts as ANSI).
$times = [string][char]0x00D7

$before = @{}
foreach ($row in (Import-Csv $Baseline)) { $before[$row.case] = $row }
$after = @(Import-Csv $Results)
if ($after.Count -eq 0) { throw "$Results is empty." }

function Num([string]$Text) { if ($Text) { [double]::Parse($Text, $inv) } else { $null } }
function Fmt([object]$Value, [string]$Format) { if ($null -eq $Value) { '' } else { ([double]$Value).ToString($Format, $inv) } }

$groups = [ordered]@{ 'Video' = 'video_*'; 'Audio' = 'audio_*'; 'Images' = 'img_*'; 'Startup' = 'startup_*' }
$lines = New-Object System.Collections.Generic.List[string]
$first = $after[0]
$lines.Add('# Final benchmark: fast-convert vs. upstream')
$lines.Add('')
$lines.Add("Generated by ``bench/make-report.ps1`` from ``$(Split-Path $Baseline -Leaf)`` (baseline, commit $($before.Values | Select-Object -First 1 -ExpandProperty commit)) and ``$(Split-Path $Results -Leaf)`` (label ``$($first.label)``, commit $($first.commit)).")
$lines.Add('')
$lines.Add('- Machine: Ryzen 9 7950X3D (16 cores, 32 threads), RTX 5070 Ti + Radeon iGPU, 64 GB, NVMe SSD.')
$lines.Add('- Baseline: upstream `integration` plus the ffmpeg stdout-deadlock fix (the untouched upstream build hangs on')
$lines.Add('  long video jobs, see `bench/README.md`), at its defaults: 2 simultaneous conversions, hardware acceleration Off.')
$lines.Add("- Final: this branch at its defaults: hardware acceleration Auto, stream copy on, image engine Auto (libvips),")
$lines.Add("  simultaneous conversions Auto ($($first.max_simultaneous) = automatic).")
$lines.Add('- Times are wall-clock seconds from launch to exit (including ~0.8 s of application startup), median of 3 runs')
$lines.Add('  for the final run and for the baseline image rows. Sizes are the total output size.')
$lines.Add('')

$allSpeedups = @()
foreach ($group in $groups.Keys) {
    $rows = @($after | Where-Object { $_.case -like $groups[$group] })
    if ($rows.Count -eq 0) { continue }
    $lines.Add("## $group")
    $lines.Add('')
    $lines.Add('| Case | Preset | Files | Baseline (s) | Final (s) | Speedup | Baseline size (MB) | Final size (MB) | Size | Status | Final output |')
    $lines.Add('|---|---|---:|---:|---:|---:|---:|---:|---:|---|---|')
    foreach ($row in $rows) {
        $b = $before[$row.case]
        $t0 = if ($b) { Num $b.seconds } else { $null }
        $t1 = Num $row.seconds
        $s0 = if ($b) { Num $b.output_mb } else { $null }
        $s1 = Num $row.output_mb
        $speedup = if ($t0 -and $t1) { $t0 / $t1 } else { $null }
        if ($speedup -and $row.case -notlike 'startup_*') { $allSpeedups += $speedup }
        $sizeChange = if ($s0 -and $s1) { ('{0:+0;-0;0} %' -f (($s1 / $s0 - 1) * 100)) } else { '' }
        $speedText = if ($speedup) { '**' + (Fmt $speedup '0.0') + "$times**" } else { '' }
        $notes = ($row.notes -replace '; runs: .*$', '') -replace '\|', '/'
        $status = if ($b -and $b.status -ne 'ok') { "$($row.status) (baseline: $($b.status))" } else { $row.status }
        $lines.Add("| ``$($row.case)`` | $($row.preset) | $($row.inputs) | $(Fmt $t0 '0.0') | $(Fmt $t1 '0.0') | $speedText | $(Fmt $s0 '0.0') | $(Fmt $s1 '0.0') | $sizeChange | $status | $notes |")
    }
    $lines.Add('')
}

if ($allSpeedups.Count -gt 0) {
    $log = 0.0; foreach ($s in $allSpeedups) { $log += [Math]::Log($s) }
    $geomean = [Math]::Exp($log / $allSpeedups.Count)
    $lines.Add('## Summary')
    $lines.Add('')
    $lines.Add(("- {0} cases (startup excluded): geometric mean speedup **{1}{4}**, from {2}{4} to {3}{4}." -f $allSpeedups.Count, (Fmt $geomean '0.0'), (Fmt ($allSpeedups | Measure-Object -Minimum).Minimum '0.0'), (Fmt ($allSpeedups | Measure-Object -Maximum).Maximum '0.0'), $times))
    $failed = @($after | Where-Object { $_.status -ne 'ok' })
    $lines.Add("- Status: $($after.Count - $failed.Count) / $($after.Count) cases ok$(if ($failed.Count) { ' (not ok: ' + (($failed | ForEach-Object { $_.case }) -join ', ') + ')' }).")
    $lines.Add('')
}

# Hand-written analysis, kept across regenerations.
$notes = Join-Path $here 'REPORT-notes.md'
if (Test-Path $notes) { $lines.AddRange([string[]](Get-Content -Encoding UTF8 $notes)) }

[IO.File]::WriteAllLines($Output, $lines, (New-Object Text.UTF8Encoding $false))
Write-Host "Written $Output"
